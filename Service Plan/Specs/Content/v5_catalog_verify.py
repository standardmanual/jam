# ① 계열 수 · 종 수
def walk_fams():
    """(종목, 축, code, name, kind, 종수, 원자료) 튜플을 순회한다."""
    for g in d['걷기']['계열']:
        for f in g['fams']:
            if f.get('ladder'):
                yield ('걷기', g['axis'], f['code'], f['name'], '등급형', len(f['ladder']), f)
            elif f.get('lv'):
                vals = parse_values(f.get('cond', ''))
                kind = '무한레벨' if vals else '자동상승'
                yield ('걷기', g['axis'], f['code'], f['name'], kind, len(vals) if vals else None, f)
    for sp in d['four종목']['종목']:
        for g in sp['groups']:
            for f in g['fams']:
                if f.get('L'):
                    yield (sp['name'], g['axis'], f['code'], f['name'], '등급형', len(f['L']), f)
                elif f.get('lv'):
                    vals = parse_values(f.get('v', ''))
                    kind = '무한레벨' if vals else '자동상승'
                    yield (sp['name'], g['axis'], f['code'], f['name'], kind, len(vals) if vals else None, f)

def parse_values(s):
    if not s or s == '—':
        return []
    parts = [x.replace('…', '').strip() for x in s.split('·')]
    parts = [x for x in parts if x]
    return parts if len(parts) > 1 else []

