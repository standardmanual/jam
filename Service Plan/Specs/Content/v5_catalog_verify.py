MIN_LEVEL = 3   # 걷기 확정본이 실제로 만족하는 구간 — Lv.1~2는 온보딩이라 의도적으로 촘촘하다

def apply_adjust(sport):
    seq = {k: (m, list(v)) for k, (m, v) in SEQ_DESIGN[sport].items()}
    for lane, mods in ADJUST.get(sport, {}).items():
        for lv, val in mods.items():
            seq[lane][1][lv - 1] = val
    return seq

def timeline(sport, seq):
    b = BASE[sport]
    pts = []
    for lane, (metric, vals) in seq.items():
        for i, v in enumerate(vals, 1):
            pts.append({'lane': lane, 'level': i, 'value': v,
                        'at': round(v / b['per'][metric], 3)})
    pts.sort(key=lambda p: p['at'])
    minint = round(3.0 / b['freq'], 3)
    viol = []
    prev = None
    for p in pts:
        if p['level'] < MIN_LEVEL:
            p['gap'] = None
            continue
        p['gap'] = round(p['at'] - prev['at'], 3) if prev else None
        if p['gap'] is not None and p['gap'] < minint - 1e-6:
            viol.append({'앞': f"{prev['lane']} Lv.{prev['level']}={prev['value']}",
                         '뒤': f"{p['lane']} Lv.{p['level']}={p['value']}",
                         '간격': p['gap'], '기준': minint})
        prev = p
    return {'단위': b['unit'], '최소간격': minint,
            '최소간격_근거': f"활동 3회분 = 주{b['freq']:.0f}회 기준 {minint}{b['unit']}",
            '검사구간': f'Lv.{MIN_LEVEL} 이상',
            '수열': pts, '위반': viol}

