    RAISE EXCEPTION '옛 컬렉션을 이름으로 한 건씩 찾지 못한 것이 %개입니다(기대: 44개 모두 1건). 이름이 이미 바뀌었거나 같은 이름이 둘 이상 있습니다.', v_bad;
  END IF;

  SELECT count(*) INTO v_bad FROM _jam2_backup_plan WHERE badge_matches IS DISTINCT FROM 1;
  IF v_bad > 0 THEN
    RAISE EXCEPTION '옛 아이템 배지 행을 컬렉션 안에서 이름으로 한 건씩 찾지 못한 것이 %개입니다(기대: 396개 모두 1건).', v_bad;
  END IF;

  SELECT count(*) INTO v_bad
    FROM (SELECT p.book_id FROM _jam2_backup_plan p GROUP BY p.book_id
           HAVING (SELECT count(*) FROM public.badges b WHERE b.item_book_id = p.book_id) <> 9) x;
  IF v_bad > 0 THEN
    RAISE EXCEPTION '아이템 배지가 9개가 아닌 옛 컬렉션이 %개 있습니다.', v_bad;
  END IF;
END $$;

