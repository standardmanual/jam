  IF v_n <> 10 THEN RAISE EXCEPTION '끝 검사: 컬렉션 백업이 %건입니다(기대 10).', v_n; END IF;
  SELECT count(*) INTO v_n FROM public.content_overwrite_backup_20261022 WHERE target_tribe = '한입만 연구회' AND kind = 'badge';
  IF v_n <> 90 THEN RAISE EXCEPTION '끝 검사: 배지 백업이 %건입니다(기대 90).', v_n; END IF;
  SELECT count(*) INTO v_n FROM public.content_overwrite_backup_20261022 WHERE target_tribe = '한입만 연구회' AND kind = 'new_item_book';
  IF v_n <> 0 THEN RAISE EXCEPTION '끝 검사: 새 컬렉션 기록이 %건입니다(기대 0).', v_n; END IF;
  SELECT count(*) INTO v_n FROM public.content_overwrite_backup_20261022 WHERE target_tribe = '한입만 연구회' AND kind = 'new_badge';
  IF v_n <> 270 THEN RAISE EXCEPTION '끝 검사: 새 배지 기록이 %건입니다(기대 270).', v_n; END IF;
