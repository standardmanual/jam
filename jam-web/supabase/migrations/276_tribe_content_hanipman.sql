DECLARE
  v_bad INTEGER;
BEGIN
  SELECT count(*) INTO v_bad FROM _jam2_book WHERE old_name IS NOT NULL AND book_matches IS DISTINCT FROM 1;
  IF v_bad > 0 THEN
    RAISE EXCEPTION '옛 컬렉션을 이름으로 한 건씩 찾지 못한 것이 %개입니다(기대: 10개 모두 1건). 이름이 이미 바뀌었거나 같은 이름이 둘 이상 있습니다.', v_bad;
