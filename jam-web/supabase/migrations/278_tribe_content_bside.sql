-- ----------------------------------------------------------------
-- 6. 끝 검사 — 어긋나면 오류로 멈추고 트랜잭션 전체가 되돌아간다
-- ----------------------------------------------------------------
DO $$
DECLARE
  v_n INTEGER;
BEGIN
  -- 컬렉션 10개: 새 이름·서사·트라이브, 활성, 4등급, 비운 칸(이미지·배경 포함)
  SELECT count(*) INTO v_n
    FROM public.item_books ib
    JOIN _jam2_book k ON k.book_id = ib.id
   CROSS JOIN _jam2_ctx c
   WHERE ib.name = k.new_name AND ib.description = k.summary AND ib.tribe_id = c.tribe_id
     AND ib.is_active AND ib.tier_mode
     AND ib.story_text IS NULL AND ib.image_url IS NULL AND ib.image_source IS NULL
     AND ib.background_color IS NULL AND ib.background_shader_id IS NULL AND ib.background_image_url IS NULL AND ib.background_video_url IS NULL AND ib.background_animation IS NULL;
  IF v_n <> 10 THEN
    RAISE EXCEPTION '끝 검사: 새 값을 가진 컬렉션이 %개입니다(기대 10).', v_n;
  END IF;

  -- 컬렉션 안의 배지 전체 360개
  SELECT count(*) INTO v_n FROM public.badges b WHERE b.item_book_id IN (SELECT book_id FROM _jam2_book);
  IF v_n <> 360 THEN
    RAISE EXCEPTION '끝 검사: 컬렉션 안의 배지가 %개입니다(기대 360).', v_n;
  END IF;

  -- 이름·등급·설명·트라이브가 원고와 같고, 이미지와 배경이 없고, 삭제되지 않은 배지
  SELECT count(*) INTO v_n
    FROM public.badges b
    JOIN _jam2_book k ON k.book_id = b.item_book_id
    JOIN _jam2_item i ON i.book_no = k.no AND i.name = b.name
   CROSS JOIN _jam2_ctx c
   WHERE b.type = 'item' AND b.tribe_id = c.tribe_id AND b.deleted_at IS NULL
     AND b.image_url IS NULL AND b.image_source IS NULL
     AND b.background_color IS NULL AND b.background_shader_id IS NULL AND b.background_image_url IS NULL AND b.background_video_url IS NULL AND b.background_animation IS NULL
     AND b.description = CASE b.rarity WHEN 'common' THEN i.d_common WHEN 'rare' THEN i.d_rare WHEN 'epic' THEN i.d_epic ELSE i.d_mystic END;
  IF v_n <> 360 THEN
    RAISE EXCEPTION '끝 검사: 원고와 같은 배지가 %개입니다(기대 360).', v_n;
  END IF;

  -- 등급마다 90개
  SELECT count(*) INTO v_n
    FROM (SELECT b.rarity FROM public.badges b
           WHERE b.item_book_id IN (SELECT book_id FROM _jam2_book)
           GROUP BY b.rarity HAVING count(*) = 90) x;
  IF v_n <> 4 THEN
    RAISE EXCEPTION '끝 검사: 등급마다 90개인 등급이 %개입니다(기대 4).', v_n;
  END IF;

  -- 같은 컬렉션의 같은 이름이 4등급 모두 있다
  SELECT count(*) INTO v_n
    FROM (SELECT b.item_book_id, b.name FROM public.badges b
           WHERE b.item_book_id IN (SELECT book_id FROM _jam2_book)
           GROUP BY b.item_book_id, b.name HAVING count(DISTINCT b.rarity) = 4 AND count(*) = 4) x;
  IF v_n <> 90 THEN
    RAISE EXCEPTION '끝 검사: 4등급이 모두 있는 이름이 %개입니다(기대 90).', v_n;
  END IF;

  -- 백업 건수
  SELECT count(*) INTO v_n FROM public.content_overwrite_backup_20261022 WHERE target_tribe = '비사이드 레코즈' AND kind = 'item_book';
  IF v_n <> 6 THEN RAISE EXCEPTION '끝 검사: 컬렉션 백업이 %건입니다(기대 6).', v_n; END IF;
  SELECT count(*) INTO v_n FROM public.content_overwrite_backup_20261022 WHERE target_tribe = '비사이드 레코즈' AND kind = 'badge';
  IF v_n <> 54 THEN RAISE EXCEPTION '끝 검사: 배지 백업이 %건입니다(기대 54).', v_n; END IF;
  SELECT count(*) INTO v_n FROM public.content_overwrite_backup_20261022 WHERE target_tribe = '비사이드 레코즈' AND kind = 'new_item_book';
  IF v_n <> 4 THEN RAISE EXCEPTION '끝 검사: 새 컬렉션 기록이 %건입니다(기대 4).', v_n; END IF;
  SELECT count(*) INTO v_n FROM public.content_overwrite_backup_20261022 WHERE target_tribe = '비사이드 레코즈' AND kind = 'new_badge';
  IF v_n <> 306 THEN RAISE EXCEPTION '끝 검사: 새 배지 기록이 %건입니다(기대 306).', v_n; END IF;
END $$;

