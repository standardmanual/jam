)
SELECT nb.id, nb.name, nb.description, 'item'::public.badge_type, nb.rarity::public.badge_rarity, k.book_id, c.tribe_id,
       o.activity_types, o.category, o.admin_category, o.patch_available, o.patch_price_krw,
