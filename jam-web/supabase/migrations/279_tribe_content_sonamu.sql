   SET book_matches = (SELECT count(*) FROM public.item_books ib WHERE ib.name = k.old_name),
       book_id      = (SELECT ib.id FROM public.item_books ib WHERE ib.name = k.old_name ORDER BY ib.created_at LIMIT 1)
