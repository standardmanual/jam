  IF v_n <> 0 THEN RAISE EXCEPTION '끝 검사: 새 컬렉션 기록이 %건입니다(기대 0).', v_n; END IF;
  SELECT count(*) INTO v_n FROM public.content_overwrite_backup_20261022 WHERE target_tribe = '소나무 잡화점' AND kind = 'new_badge';
