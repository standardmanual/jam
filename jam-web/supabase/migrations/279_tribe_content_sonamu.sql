     AND (SELECT count(*) FROM public.badges b WHERE b.item_book_id = k.book_id) <> 9;
  IF v_bad > 0 THEN
    RAISE EXCEPTION '아이템 배지가 9개가 아닌 옛 컬렉션이 %개 있습니다.', v_bad;
  END IF;

  SELECT count(*) INTO v_bad
    FROM public.user_item_book_slots s
    JOIN public.badges b ON b.id = s.badge_id
